"""Package the Azure Function as one zip, ready for `az functionapp deployment source config-zip`.

    python deploy/azure_function/build.py

Writes dist/compliance_ai_function.zip containing function_app.py, host.json, config.yaml,
the compliance_ai package, the trained model, the drift reference profile, sample requests,
a requirements.txt pinned to the versions installed HERE (so the pickled model loads the
same way in Azure) and .python_version (the Python version to create the Function App with).

Python's zipfile is used on purpose: Windows PowerShell's Compress-Archive can write
backslashes into paths, which breaks the Linux build in Azure.
"""
from __future__ import annotations

import json
import sys
import zipfile
from importlib import metadata
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DIST = ROOT / "dist"
ZIP_PATH = DIST / "compliance_ai_function.zip"

# Packages the scoring path imports (credit.predict, credit.explain, monitoring, batch file reading).
RUNTIME_PACKAGES = ["numpy", "pandas", "scipy", "scikit-learn", "shap", "PyYAML", "joblib",
                    "pdfplumber", "openpyxl"]
SUPPORTED_PYTHON = {"3.10", "3.11", "3.12", "3.13", "3.14"}   # Azure Functions on Linux, Flex Consumption


def pinned_requirements(needs_xgboost: bool) -> str:
    lines = ["# Generated by build.py from the local environment - versions match the trained model.",
             "azure-functions"]
    for name in RUNTIME_PACKAGES:
        lines.append(f"{name}=={metadata.version(name)}")
    if needs_xgboost:
        # xgboost-cpu is the same library without the ~200 MB CUDA/NCCL dependency.
        lines.append(f"xgboost-cpu=={metadata.version('xgboost')}")
    return "\n".join(lines) + "\n"


def sample_requests() -> tuple[dict, dict]:
    import pandas as pd

    df = pd.read_csv(ROOT / "data/raw/german_credit.csv").drop(columns=["credit_risk"])
    applicant = df.iloc[0].to_dict()
    batch = {"applicants": df.sample(60, random_state=7).to_dict(orient="records")}
    to_py = json.loads(json.dumps({"a": applicant, "b": batch}, default=lambda x: x.item()))
    return to_py["a"], to_py["b"]


def add_tree(zf: zipfile.ZipFile, folder: Path, arc_prefix: str) -> None:
    for path in sorted(folder.rglob("*")):
        if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc":
            zf.write(path, f"{arc_prefix}/{path.relative_to(folder).as_posix()}")


def main(zip_path: Path = ZIP_PATH) -> int:
    model = ROOT / "models/credit_model.joblib"
    profile = ROOT / "models/reference_profile.json"
    for needed in (model, profile):
        if not needed.exists():
            print(f"Missing {needed.relative_to(ROOT)} - run: python -m compliance_ai.credit.train")
            return 1

    py = f"{sys.version_info.major}.{sys.version_info.minor}"
    if py not in SUPPORTED_PYTHON:
        print(f"Python {py} is not available in Azure Functions. Use one of {sorted(SUPPORTED_PYTHON)}.")
        return 1

    import joblib

    bundle = joblib.load(model)
    needs_xgboost = type(bundle["pipeline"].steps[-1][1]).__module__.startswith("xgboost")
    applicant, batch = sample_requests()

    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.write(HERE / "function_app.py", "function_app.py")
        zf.write(HERE / "host.json", "host.json")
        zf.write(ROOT / "config.yaml", "config.yaml")
        add_tree(zf, ROOT / "src/compliance_ai", "compliance_ai")
        zf.write(model, "models/credit_model.joblib")
        zf.write(profile, "models/reference_profile.json")
        zf.writestr("requirements.txt", pinned_requirements(needs_xgboost))
        zf.writestr(".python_version", py + "\n")
        zf.writestr("sample_applicant.json", json.dumps(applicant, indent=2))
        zf.writestr("sample_batch.json", json.dumps(batch))

    print(f"Built {zip_path} ({zip_path.stat().st_size / 1e6:.1f} MB)")
    print(f"  model: {bundle['model_name']}  |  Python for Azure: {py}  |  xgboost: {needs_xgboost}")
    print("Next: upload this zip and deploy/azure_function/deploy_azure.sh to Azure Cloud Shell,")
    print("      then run:  bash deploy_azure.sh   (see docs/AZURE_DEPLOY.md)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
